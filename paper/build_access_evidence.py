"""Verify saved research evidence and generate the IEEE Access paper's numbers.

Run from any directory: python paper/build_access_evidence.py [--replay]
No existing experiment artifacts are overwritten. --replay also checks every
saved main-study plan against the currently saved classifier, SCM and costs.
"""
